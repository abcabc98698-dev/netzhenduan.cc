async function run() {
  let failCount = 0;
  for (const url of urls) {
    try {
      const res = await fetch(url);
      console.log(`[${res.status}] ${url}`);
      if (res.status !== 200) {
        failCount++;
      }
    } catch (err) {
      console.error(`[ERR] ${url}: ${err.message}`);
      failCount++;
    }
  }
  console.log(`\nURL Check Completed: ${urls.length - failCount}/${urls.length} Passed.`);
  process.exit(failCount === 0 ? 0 : 1);
}

